// Writes src/engine/build/fontweights.ts from public/fonts/manifest.json: the weights each family can render, so the
// text-group engine never asks for a weight the browser would have to fake. Run after changing the font set.
import { readFileSync, writeFileSync } from 'node:fs';
const m = JSON.parse(readFileSync(new URL('../public/fonts/manifest.json', import.meta.url), 'utf8'));
const rows = m.map((f) => `  ${JSON.stringify(f.family)}: [${f.variable ? `${f.wmin}, ${f.wmax}, 1` : `${JSON.stringify((f.weights.length ? f.weights : [400]).sort((a, b) => a - b))}`}]`);
writeFileSync(new URL('../src/engine/build/fontweights.ts', import.meta.url), `// Generated by scripts/build-fontweights.mjs from public/fonts/manifest.json: do not edit by hand.
// family → [min, max, 1] for variable fonts, or [[weights…]] for static ones
export const FONT_WEIGHTS: Record<string, [number, number, 1] | [number[]]> = {
${rows.join(',\n')},
};
/** the nearest weight the family can render */
export function snapWeight(family: string, want: number): number {
  const f = FONT_WEIGHTS[family];
  if (!f) return want;
  if (f.length === 3) return Math.max(f[0], Math.min(f[1], want));
  return f[0].reduce((a, b) => (Math.abs(b - want) < Math.abs(a - want) ? b : a), f[0][0]);
}
`);
