import pandas as pd, numpy as np, json
import os; os.chdir(os.path.dirname(os.path.abspath(__file__)))
from sklearn.ensemble import GradientBoostingRegressor
import sys
EXC=[a for a in sys.argv[1:]]  # sets to leave out, e.g. `python3 export.py P6` reproduces the shipped phase-6 model
d=pd.read_csv('train.csv'); d=d[~d.set.isin(EXC)].reset_index(drop=True); names=list(d.columns[3:]); X=d.iloc[:,3:].values.astype(float); y=d.y.values.astype(float)
m=GradientBoostingRegressor(n_estimators=250,max_depth=3,learning_rate=0.03,subsample=0.8,min_samples_leaf=8,random_state=0).fit(X,y)
trees=[]
for est in m.estimators_[:,0]:
    t=est.tree_
    trees.append([t.feature.tolist(),[round(float(v),5) for v in t.threshold],t.children_left.tolist(),t.children_right.tolist(),[round(float(v[0][0]),5) for v in t.value]])
init=float(m.init_.constant_[0][0]) if hasattr(m.init_,'constant_') else float(np.mean(y))
imp=sorted(zip(m.feature_importances_,names),reverse=True)[:15]
print('top features',[(n,round(v,3)) for v,n in imp])
out={'names':names,'init':round(init,5),'lr':m.learning_rate,'trees':trees,'n':len(y)}
src='// Generated by scripts/taste/export.py: gradient-boosted trees trained on the hand-rated posters of phases 3–6\n// (shipped model: `python3 scripts/taste/export.py P6`, i.e. the final phase-6 evaluation set held out).\n// Do not edit by hand.\nexport const TASTE_MODEL: { names: string[]; init: number; lr: number; n: number; trees: [number[], number[], number[], number[], number[]][] } = '+json.dumps(out,separators=(',',':'))+' as const;\n'
open('../../src/engine/aesthetic/model.ts','w').write(src); print(len(src)//1024,'KB', 'train pred mean',m.predict(X).mean())
