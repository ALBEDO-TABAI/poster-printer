"""Procedurally generate original images (abstract fluid, space, landscapes, waves, aura) for the preset library.
All outputs are original works created by this script (seeded), released with the app."""
import numpy as np, os, json, math
from PIL import Image, ImageFilter, ImageDraw
from scipy.ndimage import zoom, map_coordinates, gaussian_filter
OUT = os.path.join(os.path.dirname(__file__), 'img_raw', 'proc')
os.makedirs(OUT, exist_ok=True)
W, H = 1440, 1800

def noise(rng, h, w, scale, octaves=5, persistence=0.5):
    acc = np.zeros((h, w)); amp = 1; tot = 0
    for o in range(octaves):
        gh, gw = max(2, int(h / scale) + 3), max(2, int(w / scale) + 3)
        g = rng.random((gh, gw))
        z = zoom(g, (h / (gh - 3) * 1.0, w / (gw - 3) * 1.0), order=3)[:h, :w]
        if z.shape != (h, w):
            z = np.pad(z, ((0, h - z.shape[0]), (0, w - z.shape[1])), mode='edge')
        acc += z * amp; tot += amp; amp *= persistence; scale /= 2
    return acc / tot

def hex2(c): c = c.lstrip('#'); return np.array([int(c[i:i+2], 16) for i in (0, 2, 4)], float)

def ramp(t, stops):
    t = np.clip(t, 0, 1); cols = [hex2(s) for s in stops]; n = len(cols) - 1
    idx = np.minimum((t * n).astype(int), n - 1); f = (t * n - idx)[..., None]
    a = np.stack(cols)[idx]; b = np.stack(cols)[idx + 1]
    f = f * f * (3 - 2 * f)
    return a + (b - a) * f

def grain(img, rng, amt=6):
    return np.clip(img + rng.normal(0, amt, img.shape[:2])[..., None], 0, 255)

def save(arr, name, meta):
    Image.fromarray(arr.astype(np.uint8)).save(os.path.join(OUT, name + '.jpg'), quality=90)
    meta.append(dict(file=name + '.jpg', category=name.split('-')[0], license='Original procedural artwork generated by scripts/gen-procedural.py (CC0)'))

def fluid(seed, stops, warp=1.0):
    rng = np.random.default_rng(seed); h, w = H // 2, W // 2
    n1 = noise(rng, h, w, 260, 4); n2 = noise(rng, h, w, 260, 4)
    yy, xx = np.mgrid[0:h, 0:w].astype(float)
    q1 = noise(rng, h, w, 200, 4)
    yy2 = yy + (n1 - .5) * 420 * warp; xx2 = xx + (n2 - .5) * 420 * warp
    v = map_coordinates(q1, [np.clip(yy2, 0, h - 1), np.clip(xx2, 0, w - 1)], order=1)
    v = (v - v.min()) / (v.max() - v.min())
    v = 0.5 + 0.5 * np.sin(v * math.pi * 2.2 + n1 * 3)
    img = ramp(v, stops)
    img = np.array(Image.fromarray(img.astype(np.uint8)).resize((W, H), Image.BICUBIC)).astype(float)
    img = np.array(Image.fromarray(img.astype(np.uint8)).filter(ImageFilter.GaussianBlur(2))).astype(float)
    return grain(img, rng, 5)

def space(seed, stops, planet=None):
    rng = np.random.default_rng(seed); h, w = H, W
    n = noise(rng, h // 2, w // 2, 300, 6, .55)
    n2 = noise(rng, h // 2, w // 2, 160, 5, .5)
    neb = np.clip((n - .45) * 2.6, 0, 1) ** 1.6 * (0.6 + n2 * .8)
    neb = zoom(neb, 2, order=1)[:h, :w]
    img = ramp(np.clip(neb, 0, 1), stops)
    st = np.zeros((h, w))
    k = 2600
    ys, xs = rng.integers(0, h, k), rng.integers(0, w, k)
    st[ys, xs] = rng.random(k) ** 3 * 255
    st = gaussian_filter(st, .7) * 3
    big = np.zeros((h, w)); kb = 40
    big[rng.integers(0, h, kb), rng.integers(0, w, kb)] = 255
    big = gaussian_filter(big, 2.2) * 40
    img = img + (st + big)[..., None]
    if planet:
        cx, cy, r, c1, c2 = planet
        yy, xx = np.mgrid[0:h, 0:w]
        d = np.hypot(xx - cx, yy - cy)
        inside = d < r
        lx, ly = -0.6, -0.5
        nz = np.sqrt(np.clip(1 - (d / r) ** 2, 0, 1))
        shade = np.clip(((xx - cx) / r * lx + (yy - cy) / r * ly) + nz * .6, 0, 1)
        bands = noise(rng, h, w, 40, 3)
        bands = 0.5 + 0.5 * np.sin((yy - cy) / r * 14 + bands * 3)
        pc = ramp(bands * .6 + shade * .4, [c2, c1, '#f4e9d8'])
        pc = pc * (0.15 + 0.85 * shade[..., None])
        mask = np.clip(r - d + 1, 0, 1)[..., None]
        img = img * (1 - mask) + pc * mask
        glow = np.exp(-np.clip(d - r, 0, None) / 18) * (d > r) * 60
        img = img + glow[..., None] * hex2(c1)[None, None] / 255
    return grain(np.clip(img, 0, 255), rng, 4)

def mountains(seed, sky, layers, sun=None):
    rng = np.random.default_rng(seed); h, w = H, W
    yy = np.linspace(0, 1, h)[:, None]
    img = ramp(np.repeat(yy, w, 1), sky)
    if sun:
        sx, sy, sr, sc = sun
        Y, X = np.mgrid[0:h, 0:w]
        d = np.hypot(X - sx, Y - sy)
        disk = np.clip(sr - d, 0, 1)[..., None]
        halo = (np.exp(-d / (sr * 2.4)) * .45)[..., None]
        img = img * (1 - disk) + hex2(sc) * disk
        img = img + (hex2(sc) - img) * halo
    nL = len(layers)
    for i, col in enumerate(layers):
        base = h * (0.42 + 0.5 * (i / max(1, nL - 1)) ** 1.1)
        amp = h * (0.16 - 0.08 * i / nL)
        x = np.arange(w)
        prof = np.zeros(w)
        a = 1
        for o in range(6):
            freq = (o + 1) ** 1.8 * (1.5 + rng.random())
            ph = rng.random() * 6.28
            prof += a * np.sin(x / w * freq * 3.14 + ph)
            a *= .5
        ridge = np.abs(np.cumsum(rng.normal(0, 1, w)))
        ridge = gaussian_filter(ridge, 6); ridge = (ridge - ridge.mean()) / (ridge.std() + 1e-6)
        y0 = base - amp * (prof * .6 + ridge * .25)
        mask = (np.arange(h)[:, None] > y0[None, :]).astype(float)
        mask = gaussian_filter(mask, .8)[..., None]
        c = hex2(col)
        depth = np.clip((np.arange(h)[:, None] - y0[None, :]) / (h * .5), 0, 1)[..., None]
        lc = c * (1 - depth * .25)
        img = img * (1 - mask) + lc * mask
    return grain(img, rng, 5)

def waves(seed, bg, fg, n=60, amp=40):
    rng = np.random.default_rng(seed)
    im = Image.new('RGB', (W * 2, H * 2), bg); d = ImageDraw.Draw(im)
    ph = rng.random(4) * 6.28
    for i in range(n):
        y0 = (i + .5) / n * H * 2
        pts = []
        for x in range(0, W * 2 + 8, 8):
            t = x / (W * 2)
            y = y0 + amp * 2 * (math.sin(t * 6.28 * 1.3 + ph[0] + i * .07) + .6 * math.sin(t * 6.28 * 3.1 + ph[1] + i * .13)) * math.sin(i / n * 3.14)
            pts.append((x, y))
        d.line(pts, fill=fg, width=5)
    im = im.resize((W, H), Image.LANCZOS)
    return grain(np.array(im).astype(float), rng, 4)

def aura(seed, bg, blobs):
    rng = np.random.default_rng(seed); h, w = H // 4, W // 4
    img = np.ones((h, w, 3)) * hex2(bg)
    Y, X = np.mgrid[0:h, 0:w]
    for col in blobs:
        cx, cy = rng.random() * w, rng.random() * h
        r = (0.25 + rng.random() * .35) * w
        f = np.exp(-((X - cx) ** 2 + (Y - cy) ** 2) / (2 * r * r))[..., None] * .95
        img = img * (1 - f) + hex2(col) * f
    img = np.array(Image.fromarray(img.astype(np.uint8)).resize((W, H), Image.BICUBIC)).astype(float)
    return grain(img, rng, 9)

def dunes(seed, stops):
    rng = np.random.default_rng(seed); h, w = H // 2, W // 2
    yy, xx = np.mgrid[0:h, 0:w].astype(float)
    n = noise(rng, h, w, 300, 3)
    v = np.sin(yy / 18 + n * 14 + np.sin(xx / 140) * 2)
    v = (v + 1) / 2 * (0.4 + .6 * (yy / h)) + n * .2
    img = ramp(np.clip(v, 0, 1), stops)
    img = np.array(Image.fromarray(img.astype(np.uint8)).resize((W, H), Image.BICUBIC)).astype(float)
    return grain(img, rng, 6)

